// This program generates the message list that gogocompat_test.go iterates
// over: every message in this package, and the wrapper types of every oneof,
// paired with their gogo/protobuf counterparts in internal/gogopb.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var (
	rxMessage = regexp.MustCompile(`func \(m \*([A-Za-z0-9_]+)\) Encode\(c \*picobuf\.Encoder\) bool \{`)
	rxOneof   = regexp.MustCompile(`(?m)^func \(\*([A-Za-z0-9_]+)\) (is[A-Za-z0-9_]+)\(\)\s*\{\}`)
)

func main() {
	files, err := filepath.Glob("*.pico.go")
	check(err)
	slices.Sort(files)

	var messages []string
	var oneofs []string
	wrappers := map[string][]string{}

	for _, file := range files {
		data, err := os.ReadFile(file)
		check(err)
		source := string(data)

		for _, match := range rxMessage.FindAllStringSubmatch(source, -1) {
			messages = append(messages, match[1])
		}
		for _, match := range rxOneof.FindAllStringSubmatch(source, -1) {
			wrapper, iface := match[1], match[2]
			if _, ok := wrappers[iface]; !ok {
				oneofs = append(oneofs, iface)
			}
			wrappers[iface] = append(wrappers[iface], wrapper)
		}
	}

	slices.Sort(messages)
	messages = slices.Compact(messages)

	var out strings.Builder
	p := func(format string, args ...any) {
		fmt.Fprintf(&out, format+"\n", args...)
	}

	p("// Copyright (C) 2026 Storj Labs, Inc.")
	p("// See LICENSE for copying information.")
	p("")
	p("// Code generated by gen_gogocompat.go. DO NOT EDIT.")
	p("")
	p("// The list covers deprecated messages as well, they are still on the wire.")
	p("//lint:file-ignore SA1019 deliberate")
	p("")
	p("package pb_test")
	p("")
	p("import (")
	p("\t%q", "storj.io/common/pb")
	p("\t%q", "storj.io/common/pb/internal/gogopb")
	p(")")
	p("")
	p("// messages lists every message in the package alongside the gogo/protobuf")
	p("// generated message it must encode identically to.")
	p("var messages = []messagePair{")
	for _, name := range messages {
		p("\t{name: %q, pico: func() pb.Message { return new(pb.%s) }, gogo: func() gogoMessage { return new(gogopb.%s) }},", name, name, name)
	}
	p("}")

	for _, side := range []struct{ variable, comment, pkg string }{
		{"oneofPico", "// oneofPico lists the wrapper types of every oneof, keyed by the name of the\n// interface that the oneof field has.", "pb"},
		{"oneofGogo", "// oneofGogo is oneofPico for the gogo/protobuf side, in the same order.", "gogopb"},
	} {
		p("")
		p("%s", side.comment)
		p("var %s = map[string][]func() any{", side.variable)
		for _, iface := range oneofs {
			p("\t%q: {", iface)
			for _, wrapper := range wrappers[iface] {
				p("\t\tfunc() any { return new(%s.%s) },", side.pkg, wrapper)
			}
			p("\t},")
		}
		p("}")
	}

	check(os.WriteFile("gogocompat_messages_test.go", []byte(out.String()), 0644))
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
